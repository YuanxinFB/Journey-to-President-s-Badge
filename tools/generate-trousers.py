"""Generate a continuous straight-cut trouser mesh in model metres. Standard-library only."""
from pathlib import Path
import math,json
step=.012
xs=[-.24+i*step for i in range(41)]
ys=[.096+i*step for i in range(81)]
zs=[-.168+i*step for i in range(29)]
def smooth_min(a,b,k=.022):
 h=max(k-abs(a-b),0)/k
 return min(a,b)-h*h*k*.25
def field(x,y,z):
 pelvis=(math.sqrt((x/.214)**2+((y-.99)/.245)**2+(z/.139)**2)-1)*.139
 legs=[]
 for side in [-1,1]:
  t=max(0,min(1,(y-.13)/.73))
  center=side*(.059+.043*t)
  radius=.060+.043*t
  theta=math.atan2(z,x-center)
  crease=.0022*abs(math.sin(theta))**18
  folds=.0014*math.exp(-((y-.19)/.055)**2)*math.sin(y*72+theta*2)
  radial=math.sqrt((x-center)**2+(z/.97)**2)-radius-crease-folds
  legs.append(max(radial,.115-y,y-.94))
 d=smooth_min(pelvis,smooth_min(*legs,k=.009))
 return max(d,.115-y,y-1.043)
ny=len(ys);nz=len(zs)
coords=[(x,y,z) for x in xs for y in ys for z in zs]
values=[field(*p) for p in coords]
tetra=[(0,5,1,6),(0,1,2,6),(0,2,3,6),(0,3,7,6),(0,7,4,6),(0,4,5,6)]
positions=[];normals=[];indices=[];cache={}
def vertex(a,b):
 key=tuple(sorted((a,b)))
 if key in cache:return cache[key]
 t=values[a]/(values[a]-values[b])
 p=tuple(coords[a][j]+t*(coords[b][j]-coords[a][j]) for j in range(3))
 n=[]
 for axis in range(3):
  a1=list(p);b1=list(p);a1[axis]+=.0004;b1[axis]-=.0004
  n.append(field(*a1)-field(*b1))
 length=math.sqrt(sum(x*x for x in n)) or 1
 i=len(positions)//3;positions.extend(round(x,6) for x in p);normals.extend(round(x/length,6) for x in n);cache[key]=i;return i
def triangle(a,b,c):
 p=[positions[3*i:3*i+3] for i in (a,b,c)]
 u=[p[1][j]-p[0][j] for j in range(3)];v=[p[2][j]-p[0][j] for j in range(3)]
 cross=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]]
 if sum(cross[j]*normals[a*3+j] for j in range(3))<0:b,c=c,b
 indices.extend((a,b,c))
for x in range(len(xs)-1):
 for y in range(ny-1):
  for z in range(nz-1):
   base=(x*ny+y)*nz+z
   cube=[base,base+ny*nz,base+ny*nz+nz,base+nz,base+1,base+ny*nz+1,base+ny*nz+nz+1,base+nz+1]
   signs=[values[i]<0 for i in cube]
   if all(signs) or not any(signs):continue
   for tet in tetra:
    inside=[cube[i] for i in tet if values[cube[i]]<0];outside=[cube[i] for i in tet if values[cube[i]]>=0]
    if not inside or not outside:continue
    if len(inside)==1:triangle(*(vertex(inside[0],b) for b in outside))
    elif len(outside)==1:triangle(*(vertex(a,outside[0]) for a in inside))
    else:
     a,b=inside;c,d=outside
     q=[vertex(a,c),vertex(a,d),vertex(b,d),vertex(b,c)]
     triangle(*q[:3]);triangle(q[0],q[2],q[3])
data={"positions":positions,"normals":normals,"indices":indices}
Path("lib/uniform-trousers.js").write_text("// Generated by tools/generate-trousers.py.\nwindow.BBMTrousers="+json.dumps(data,separators=(",",":"))+";\n")
print("Continuous trousers:",len(positions)//3,"vertices,",len(indices)//3,"triangles")
